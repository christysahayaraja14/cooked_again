#!/usr/bin/env node
'use strict';

/* Reads SUPABASE_URL and SUPABASE_ANON_KEY from .env (or from real environment
   variables, e.g. on Netlify/Vercel) and writes supabase-config.js.
   Usage:  node generate-config.js                                          */

const fs = require('fs');
const path = require('path');

function parseEnv(text) {
  const out = {};
  text.split(/\r?\n/).forEach((line) => {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/);
    if (!m || line.trim().startsWith('#')) return;
    out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
  });
  return out;
}

const envPath = path.join(__dirname, '.env');
const fromFile = fs.existsSync(envPath) ? parseEnv(fs.readFileSync(envPath, 'utf8')) : {};
const url = (process.env.SUPABASE_URL || fromFile.SUPABASE_URL || '').trim().replace(/\/+$/, '');
const key = (process.env.SUPABASE_ANON_KEY || fromFile.SUPABASE_ANON_KEY || '').trim();

function fail(msg) {
  console.error('\n  x ' + msg + '\n');
  process.exit(1);
}

if (!url || /YOUR-/i.test(url)) fail('SUPABASE_URL is missing or still the placeholder. Edit .env first.');
if (!key || /YOUR-/i.test(key)) fail('SUPABASE_ANON_KEY is missing or still the placeholder. Edit .env first.');
if (!/^https:\/\/[a-z0-9-]+\.supabase\.(co|in)$/i.test(url) && !/^http:\/\/(localhost|127\.0\.0\.1)/.test(url)) {
  fail('SUPABASE_URL should look like https://xxxxxxxx.supabase.co');
}

// Safety net: refuse to publish a secret key into browser code.
if (key.startsWith('sb_secret_')) fail('That is a SECRET key. Use the anon / publishable key instead.');
if (key.split('.').length === 3) {
  try {
    const payload = JSON.parse(Buffer.from(key.split('.')[1], 'base64').toString('utf8'));
    if (payload.role === 'service_role') fail('That is the service_role key. Use the anon key instead.');
  } catch (e) {
    /* not a decodable JWT - let it through */
  }
}

const out =
  '/* supabase-config.js - GENERATED by generate-config.js. Do not edit by hand (re-run the script). */\n' +
  'window.SUPABASE_CONFIG = ' + JSON.stringify({ url: url, anonKey: key }, null, 2) + ';\n';

fs.writeFileSync(path.join(__dirname, 'supabase-config.js'), out);
console.log('\n  ok supabase-config.js written for ' + url + '\n');
